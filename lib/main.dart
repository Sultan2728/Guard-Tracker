import 'package:firebase_auth/firebase_auth.dart';
import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'models/worker.dart';
import 'services/auth_service.dart';
import 'screens/auth_screen.dart';
import 'screens/status_screen.dart';
import 'screens/worker_shift_screen.dart';
import 'screens/boss_screen.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const GuardTrackerApp());
}

class GuardTrackerApp extends StatelessWidget {
  const GuardTrackerApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Трекер охраны',
      theme: ThemeData(
        colorSchemeSeed: Colors.blue,
        useMaterial3: true,
      ),
      home: const _StartupRouter(),
    );
  }
}

/// Routes the app based on Firebase Auth sign-in state, and then on the
/// signed-in user's worker profile: not signed in -> login screen;
/// signed in but no/rejected/pending profile -> a status screen;
/// approved boss -> the boss panel; approved worker with a site ->
/// their shift screen; approved worker without a site yet -> a
/// "waiting for assignment" status screen.
class _StartupRouter extends StatelessWidget {
  const _StartupRouter();

  @override
  Widget build(BuildContext context) {
    final auth = AuthService();
    return StreamBuilder<User?>(
      stream: auth.authStateChanges,
      builder: (context, authSnap) {
        if (authSnap.connectionState == ConnectionState.waiting) {
          return const Scaffold(body: Center(child: CircularProgressIndicator()));
        }
        final user = authSnap.data;
        if (user == null) {
          return const AuthScreen();
        }
        return StreamBuilder<Worker?>(
          stream: auth.watchCurrentWorker(),
          builder: (context, workerSnap) {
            if (workerSnap.connectionState == ConnectionState.waiting) {
              return const Scaffold(body: Center(child: CircularProgressIndicator()));
            }
            final worker = workerSnap.data;
            if (worker == null) {
              // Signed in, but the profile document hasn't appeared yet
              // (e.g. right after registration) — wait a moment.
              return const Scaffold(body: Center(child: CircularProgressIndicator()));
            }
            if (worker.status == WorkerStatus.rejected) {
              return const StatusScreen(
                emoji: '🚫',
                title: 'Заявка отклонена',
                message: 'Начальник отклонил вашу заявку. Если это ошибка, свяжитесь с ним напрямую.',
              );
            }
            if (worker.isBoss) {
              return const BossScreen();
            }
            if (worker.status == WorkerStatus.pending) {
              return const StatusScreen(
                emoji: '⏳',
                title: 'Ожидайте одобрения',
                message: 'Ваша заявка отправлена начальнику. Как только он её одобрит и назначит вас на объект, здесь появится экран смены.',
              );
            }
            // approved
            if (worker.siteId == null) {
              return const StatusScreen(
                emoji: '📍',
                title: 'Объект ещё не назначен',
                message: 'Начальник одобрил вашу заявку, но ещё не назначил вас на объект. Загляните сюда позже.',
              );
            }
            return WorkerShiftScreen(worker: worker);
          },
        );
      },
    );
  }
}
