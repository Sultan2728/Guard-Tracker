import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/role_select_screen.dart';
import 'screens/guard_screen.dart';
import 'screens/boss_screen.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const GuardTrackerApp());
}

class GuardTrackerApp extends StatelessWidget {
  const GuardTrackerApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Трекер охраны',
      theme: ThemeData(
        colorSchemeSeed: Colors.blue,
        useMaterial3: true,
      ),
      home: const _StartupRouter(),
    );
  }
}

/// Reads the previously saved role from disk so the guard/boss doesn't
/// have to pick their role again every time they open the app.
class _StartupRouter extends StatelessWidget {
  const _StartupRouter();

  @override
  Widget build(BuildContext context) {
    return FutureBuilder<SharedPreferences>(
      future: SharedPreferences.getInstance(),
      builder: (context, snap) {
        if (!snap.hasData) {
          return const Scaffold(body: Center(child: CircularProgressIndicator()));
        }
        final prefs = snap.data!;
        final role = prefs.getString('role');
        if (role == 'guard') {
          final siteId = prefs.getString('siteId');
          final siteName = prefs.getString('siteName');
          final slot = prefs.getInt('slot');
          if (siteId != null && siteName != null && slot != null) {
            return GuardScreen(siteId: siteId, siteName: siteName, slot: slot);
          }
          // Incomplete saved state (e.g. from before multi-site support) —
          // fall back to picking role/site again.
          return const RoleSelectScreen();
        } else if (role == 'boss') {
          return const BossScreen();
        }
        return const RoleSelectScreen();
      },
    );
  }
}
